export const MX = { cols: 63, rows: 7, pitch: 2.5, w: 162, h: 32 }
export function matrixColumns(text: string) {
  const cols: boolean[][] = []
  for (const ch of text) {
    const g = (FONT[ch] || FONT[" "]).split(" ")
    for (let x = 0; x < 5; x++) cols.push(g.map((r) => r[x] === "1"))
    cols.push(Array(7).fill(false))
  }
  return cols
}
